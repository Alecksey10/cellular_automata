/**
 * Параметры, управляющие самим RUNTIME (не автоматом).
 * Меняются через ControlPanel или через IRuntimeCallback от автомата.
 */
export class RuntimeParams {
  /** Множитель скорости симуляции. 1.0 = норма, 2.0 = ×2 */
  speed = 1.0;

  /** Целевой FPS внутреннего цикла */
  targetFps = 30;

  /**
   * Рендерить каждые N итераций.
   * 1 = каждый кадр, 5 = каждый 5-й кадр.
   * Полезно для тяжёлых автоматов, где итерация быстрее рендера.
   */
  renderEveryN = 1;

  /** Пауза */
  paused = false;

  /**
   * Максимум итераций за один requestAnimationFrame.
   * Защита от «спирали смерти»: если вкладка была неактивна
   * и накопился большой dt, не пытаемся догнать все пропущенные кадры.
   */
  maxIterationsPerFrame = 100;

  /** Размеры сетки по умолчанию (если автомат не переопределяет) */
  defaultGridWidth = 100;
  defaultGridHeight = 100;

  /** Обновить параметры из частичного объекта */
  apply(patch: Partial<RuntimeParams>): void {
    Object.assign(this, patch);
  }
}