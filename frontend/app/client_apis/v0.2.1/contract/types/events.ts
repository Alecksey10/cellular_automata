/**
 * Событие, которое автомат отправляет в RUNTIME
 * через IRuntimeCallback.emitEvent().
 *
 * RUNTIME пересылает его через EventBus → EventLogPanel.
 */
export interface AutomatonEvent {
  /**
   * Тип события (влияет на отображение в UI):
   *
   * - "info"    → нейтральное сообщение (синий бейдж)
   * - "warning" → предупреждение (жёлтый бейдж)
   * - "error"   → ошибка (красный бейдж, может триггерить остановку)
   * - "request" → автомат просит что-то у среды
   *               (например, "увеличь сетку", "загрузи данные")
   */
  type: "info" | "warning" | "error" | "request";

  /** Человекочитаемое сообщение */
  message: string;

  /** Произвольные данные (для продвинутой обработки) */
  data?: unknown;
}